DOT.lang = 'ar';
DOT.t = function (key, vars) {
  var d = DOT.i18n[DOT.lang] || DOT.i18n.ar;
  var s = d[key] != null ? d[key] : (DOT.i18n.en[key] != null ? DOT.i18n.en[key] : key);
  if (vars) for (var k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};
DOT.applyLang = function (lang) {
  DOT.lang = DOT.i18n[lang] ? lang : 'ar';
  var html = document.documentElement;
  html.lang = DOT.lang; html.dir = DOT.lang === 'ar' ? 'rtl' : 'ltr';
  Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function (el) { el.textContent = DOT.t(el.getAttribute('data-i18n')); });
  Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-html]'), function (el) { el.innerHTML = DOT.t(el.getAttribute('data-i18n-html')); });
};
